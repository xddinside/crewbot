// Reads the real skin blocks out of src/styles.css and emits them as a CSS
// block for the visual proof, so the preview cannot drift from the shipped
// palette. Run: node scripts/build-sky-proof.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const css = readFileSync(join(root, "src/styles.css"), "utf8");

function declarations(body) {
  const tokens = {};
  for (const [, name, value] of body.matchAll(/(--[\w-]+)\s*:\s*([^;]+);/g)) {
    tokens[name] = value.trim();
  }
  return tokens;
}

const base = {};
for (const [, body] of css.matchAll(/:root\s*\{([^}]*)\}/g)) Object.assign(base, declarations(body));

const skins = {};
for (const id of ["daylight", "midnight"]) {
  const body = css.match(new RegExp(`\\[data-skin="${id}"\\]\\s*\\{([^}]*)\\}`))?.[1] ?? "";
  skins[id] = { ...base, ...declarations(body) };
}

const want = [
  "--sky-ground", "--sky-ink", "--sky-ink-soft", "--sky-opacity",
  "--glass-bg", "--glass-border", "--glass-ring", "--glass-shadow",
  "--color-app", "--color-panel", "--color-raised", "--color-raised-hover",
  "--color-card", "--color-inset", "--color-hairline", "--color-ink",
  "--color-ink-secondary", "--color-accent", "--color-accent-ink",
  "--color-composer", "--color-composer-ring", "--color-bubble-user",
  "--color-bubble-user-ink", "--color-scrollbar",
  "--mascot-maus", "--mascot-atlas", "--mascot-nova", "--mascot-sage",
  "--font-sans",
];

let out = "/* generated by scripts/build-sky-proof.mjs — do not edit */\n";
for (const [id, tokens] of Object.entries(skins)) {
  out += `[data-skin="${id}"]{`;
  for (const name of want) if (tokens[name]) out += `${name}:${tokens[name]};`;
  out += "}\n";
}
writeFileSync(join(root, "scripts/sky-proof-skins.css"), out);
console.log(`wrote scripts/sky-proof-skins.css (${Object.keys(skins).length} skins)`);